#!/usr/bin/env python3
"""Build the small committed sample + plant library from the full dataset.

    python3 tools/make_sample.py /path/to/hotel_garden_water_ai_complete_dataset

Writes (stdlib only, deterministic):
    data/sample/{garden_zones,hotels,irrigation_history}.csv   12 hotels, 3 per size class
    data/sample/sample.js                                      same tables as window.HG_SAMPLE
    data/plants.js                                             window.HG_PLANTS from plant_master.csv

The full 36 MB dataset is deliberately NOT committed (see docs/DATASET.md).
"""
import csv, json, os, sys

src = sys.argv[1] if len(sys.argv) > 1 else "."
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "data")
os.makedirs(os.path.join(out, "sample"), exist_ok=True)

def read(name):
    with open(os.path.join(src, name), encoding="utf-8-sig", newline="") as f:
        r = csv.DictReader(f)
        return r.fieldnames, list(r)

def write(path, fields, rows):
    with open(path, "w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fields, lineterminator="\n")
        w.writeheader(); w.writerows(rows)

hf, hotels = read("hotels.csv")
zf, zones = read("garden_zones.csv")
ff, hist = read("irrigation_history.csv")

picked = []
for size in ["Small", "Medium", "Large", "Resort"]:
    group = sorted((h for h in hotels if h["hotel_size"] == size), key=lambda h: h["hotel_id"])
    step = len(group) // 3
    picked += [group[step // 2 + i * step] for i in range(3)]
ids = {h["hotel_id"] for h in picked}

tables = {
    "hotels": (hf, [h for h in hotels if h["hotel_id"] in ids]),
    "garden_zones": (zf, [z for z in zones if z["hotel_id"] in ids]),
    "irrigation_history": (ff, [e for e in hist if e["hotel_id"] in ids]),
}
for name, (fields, rows) in tables.items():
    write(os.path.join(out, "sample", name + ".csv"), fields, rows)

def text(name):
    with open(os.path.join(out, "sample", name + ".csv"), encoding="utf-8") as f:
        return f.read()

with open(os.path.join(out, "sample", "sample.js"), "w", encoding="utf-8") as f:
    f.write("/* Generated by tools/make_sample.py — 12 synthetic hotels. Do not edit. */\n")
    f.write("window.HG_SAMPLE = " + json.dumps({k: text(k) for k in tables}, ensure_ascii=False) + ";\n")

_, plants = read("plant_master.csv")
lib = [[p["plant_id"], p["common_name"], p["water_need_class"], float(p["prototype_plant_factor"]),
        float(p["heat_stress_threshold_c"])] for p in plants]
with open(os.path.join(out, "plants.js"), "w", encoding="utf-8") as f:
    f.write("/* Generated by tools/make_sample.py from plant_master.csv. [id, name, water class, Kc, heat-stress C].\n"
            "   Kc values are PROTOTYPE class factors, not species-validated. */\n")
    f.write("window.HG_PLANTS = " + json.dumps(lib, ensure_ascii=False, separators=(",", ":")) + ";\n")
print(f"{len(picked)} hotels, {len(tables['garden_zones'][1])} zones, {len(lib)} plants")
